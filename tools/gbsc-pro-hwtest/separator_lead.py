#!/usr/bin/env python3
"""What the sync separator costs the capture origin, read twice per mode.

    python3 tools/gbsc-pro-hwtest/separator_lead.py --host <ip> \\
        --modeserv 192.168.88.10 --mode "X320 Y256 C256 F70"

A source whose hsync is regenerated by the separator -- composite sync and sync
on green both -- reaches the input formatter's counter late, so
`VideoSourceLine::forDuty()` opens its capture window earlier by the measured
sync width less `SeparatorPulseEndLeadSamples`, in ADC samples.

Two readings per mode, and they answer different questions:

    applied     IF_HB_ST2 on the two sync types, differenced. What the engine
                DID, against what the form says it should do.
    residual    the card's black margin at one edge on the two sync types,
                differenced and divided by the magnification. What is LEFT
                after the lead has been applied, in ADC samples of the source.

**BOTH READINGS ARE DIFFERENCES ON ONE MODE.** A position read against a
published raster carries that mode's own systematic -- whether the machine emits
the raster the file states, where the sink placed its window, where the counter's
origin sits -- and only the difference between the two sync types is the
separator.

**THE DIFFERENCE MUST BE AT THE SAME EDGE.** Where one sync type leaves a margin
at the near edge and the other runs off it, the two readings measure different
features and differencing them gives a number with no meaning. A mode with no
edge on the frame under both sync types is reported as carrying no residual.

**A COLUMN IS WORTH A CAPTURE UNIT ONLY WHILE THE PICTURE FILLS THE FRAME.** The
sink chooses its own window and stretches it to the frame it transmits, so what
a dongle column is worth is not the magnification the registers state: measured
at 320x256@50 into 1080p the picture spans 1916 columns where the registers put
it at 1674 output units. The conversion used is the emitted frame over the
capture window's extent, which carries that stretch and holds while the picture
is near flush -- the only state a default framing is judged in. A column read
on a letterboxed or heavily panned picture is not worth this.

docs/investigations/the-separator-lead-is-not-a-fraction-of-the-line.md
"""
import argparse
import math
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import card_edges
import framing_decomposition
import gbs_unit
import hdmi_capture

# VideoSourceLine.h, so a measured lead can be scored against the form in force.
SEPARATOR_PULSE_END_LEAD_SAMPLES = 66

# VideoSourceLine::DoubledHeadBlankingUnits, which with the sync width is the
# first unit a window may open on. A composite leg sitting on that floor has had
# its lead truncated and measures the floor instead.
DOUBLED_HEAD_BLANKING_UNITS = 22

# CaptureWindow::captureOn()'s margin at each end of the horizontal axis.
CAPTURE_MARGIN_H = 1

# SyncProcessor::InvertedPulseWidthSamples, which hsyncPulseSamples() takes off
# a reading the path widened -- a positive-going source or a separated one. The
# lead is computed from THAT pulse, so a prediction made from the register alone
# is five samples long and reads as rounding.
INVERTED_PULSE_WIDTH_SAMPLES = 5

# A sync-type change leaves the engine on the path it held, and the re-probe is a
# detection sweep -- so a case pays for the source leaving and returning.
SETTLE_SECONDS = 14.0

FIELDS = ["STATUS_SYNC_PROC_HLOW_LEN", "PLLAD_MD", "STATUS_SYNC_PROC_HTOTAL",
          "IF_HB_SP2", "IF_HB_ST2", "IF_HSYNC_RST", "SP_SOG_MODE",
          "SP_CS_HS_SP", "SP_RT_HS_SP", "VDS_HSCALE", "VDS_VSCALE",
          "VDS_VSYNC_RST", "STATUS_SYNC_PROC_HSPOL"]

Axes = (("across", 1), ("down", 0))

# What the source is left showing, which is nobody's choice otherwise: a run
# ends on whatever mode and sync type its last leg used.
BENCH_MODE = "X320 Y256 C256 F50"


def samples_per_unit(registers):
    """ADC samples to one counter unit, asked of the counter itself.

    **NOT THE LINE RATE.** The doubler is selected on the source's LINE COUNT
    (InputFormatter::shouldDoubleLine, under 400 lines), so 640x352@60 at
    21.9 kHz is doubled where /geometry's `lowLineRate` says it is not. What the
    unit is worth is IF_HSYNC_RST against the divider: halved where the line is
    doubled and equal where it is not.
    """
    units = registers["IF_HSYNC_RST"] + 1
    return 2 if units and registers["PLLAD_MD"] / units > 1.5 else 1


def pulse_samples(registers, separated):
    """The pulse the engine computes the lead from: the shorter of the low time
    and its complement, less the calibration a widened path adds."""
    low = registers["STATUS_SYNC_PROC_HLOW_LEN"]
    line = registers["PLLAD_MD"]
    folded = min(low, line - low) if line > low else low
    widened = registers["STATUS_SYNC_PROC_HSPOL"] or separated
    if widened and folded > INVERTED_PULSE_WIDTH_SAMPLES:
        folded -= INVERTED_PULSE_WIDTH_SAMPLES
    return folded


def sync_units(registers, separated):
    units = registers["IF_HSYNC_RST"] + 1
    duty = pulse_samples(registers, separated) / registers["PLLAD_MD"]
    return math.ceil(units * duty)


def predicted_lead(registers, spu):
    """What VideoSourceLine::forDuty() computes for the separated leg, in units."""
    samples = sync_units(registers, True) * spu
    if samples <= SEPARATOR_PULSE_END_LEAD_SAMPLES:
        return 0
    return (samples - SEPARATOR_PULSE_END_LEAD_SAMPLES) // spu


def capture_floor(registers, spu, separated):
    """The first unit a window may open on: the head blanking the doubled path
    writes past the pulse, plus the pulse itself."""
    head = DOUBLED_HEAD_BLANKING_UNITS if spu == 2 else 0
    return head + sync_units(registers, separated)


def leg(host, where, device, mode, csync):
    """One sync type of one mode: the registers, the emitted frame's edges and
    the state they were read in."""
    gbs_unit.set_sync_type(where, csync)
    reply = gbs_unit.mode_serv(where, f"MODE {mode}")
    if not gbs_unit.modeserv_ok(reply):
        return {"why": f"the source refused the mode: {reply!r}"}
    # establishSyncType() keys on the input selection, so the engine follows a
    # SYNC command only once something makes it probe again.
    gbs_unit.get(host, "/sc?~")
    time.sleep(SETTLE_SECONDS)
    if not gbs_unit.acquired_and_settled(host, limit_s=90.0):
        return {"why": "never acquired, or never stopped re-solving"}
    if not gbs_unit.show_card(where):
        return {"why": "the source would not draw the card"}
    if gbs_unit.reset_framing(host) is None:
        return {"why": "the framing never reset"}
    # AFTER the reset, which puts the declared shape back to the raster's own
    # default -- 4:3, whose bars are our blanking and read as hundreds of
    # columns at the near edge.
    if not gbs_unit.choose_aspect(host, gbs_unit.SIXTEEN_NINE):
        return {"why": "the shape never reached 16:9"}

    registers = gbs_unit.read_fields(host, FIELDS)
    _, geometry = gbs_unit.get_json(host, "/geometry")
    emitted = framing_decomposition.carried_frame(registers)
    if emitted is None:
        return {"why": "the registers carry no output mode this knows"}
    clip = hdmi_capture.frames(card_edges.CLIP_FRAMES, device,
                               width=emitted[0], height=emitted[1])
    found = {name: card_edges.judge(clip, axis, card_edges.ALLOWANCE,
                                    card_edges.source_pixel_px(mode, clip, axis))
             for name, axis in Axes}
    return {"why": None, "registers": registers, "geometry": geometry,
            "emitted": emitted, "found": found}


def applied(sep, cs):
    """The window's displacement between the two sync types, in ADC samples, and
    what the form in force predicts for it."""
    spu = samples_per_unit(sep["registers"])
    units = sep["registers"]["IF_HB_ST2"] - cs["registers"]["IF_HB_ST2"]
    return units, units * spu, predicted_lead(cs["registers"], spu)


def truncated(cs):
    """Whether the composite leg's window opens on its floor, in which case the
    lead was cut short and the difference measures the floor."""
    spu = samples_per_unit(cs["registers"])
    floor = capture_floor(cs["registers"], spu, True)
    start = cs["registers"]["IF_HB_SP2"] + CAPTURE_MARGIN_H
    return start <= floor + 1, start, floor


def residual(sep, cs, name, columns):
    """What the emitted frame still shows between the two sync types at one
    edge, in ADC samples of the source.

    Positive is the composite picture sitting further into the frame than the
    separate one -- the lead over-compensating, which wants a LARGER constant.
    """
    spu = samples_per_unit(sep["registers"])
    extent = sep["geometry"].get("eh" if name == "across" else "ev")
    if not extent:
        return None, "no capture extent"
    per_unit = columns / float(extent)
    for end, index, sign in (("near", 0, 1.0), ("far", 1, -1.0)):
        at_sep = sep["found"][name].margins[index]
        at_cs = cs["found"][name].margins[index]
        if at_sep is None or at_cs is None:
            continue
        return (sign * (at_cs - at_sep) / per_unit * spu,
                f"{end} edge, {at_sep} vs {at_cs} columns at "
                f"{per_unit:.3f} per unit, {spu} samples per unit")
    return None, "no edge on the frame under both sync types"


def report(mode, legs):
    sep, cs = legs[False], legs[True]
    print(f"\n{mode}")
    for csync, one in ((False, sep), (True, cs)):
        label = "composite" if csync else "separate"
        if one["why"]:
            print(f"  {label:10} {one['why']}")
            continue
        r, g = one["registers"], one["geometry"]
        read = "  ".join(f"{name} {card_edges.reading(one['found'][name])}"
                         for name, _ in Axes)
        print(f"  {label:10} MD {r['PLLAD_MD']} HLOW "
              f"{r['STATUS_SYNC_PROC_HLOW_LEN']} "
              f"duty {r['STATUS_SYNC_PROC_HLOW_LEN'] / r['PLLAD_MD']:.4f} "
              f"SOGM {r['SP_SOG_MODE']} POL {r['STATUS_SYNC_PROC_HSPOL']} "
              f"IF_HB {r['IF_HB_SP2']}..{r['IF_HB_ST2']} "
              f"HSCALE {r['VDS_HSCALE']} "
              f"{one['emitted'][0]}x{one['emitted'][1]} "
              f"eh {g.get('eh')} ev {g.get('ev')} "
              f"IF_HSYNC_RST {r['IF_HSYNC_RST']} "
              f"spu {samples_per_unit(r)}")
        print(f"  {'':10} {read}")
    if sep["why"] or cs["why"]:
        return
    units, samples, want = applied(sep, cs)
    print(f"  applied    {units} units = {samples} samples, "
          f"forDuty() computes {want} units")
    cut, start, floor = truncated(cs)
    if cut:
        print(f"  TRUNCATED  the composite window opens at {start} on a floor "
              f"of {floor}, so the lead is clamped and neither reading is of "
              f"the lead")
    for name, _ in Axes:
        columns = sep["emitted"][0 if name == "across" else 1]
        left, how = residual(sep, cs, name, columns)
        if left is None:
            print(f"  residual   {name}: none -- {how}")
        else:
            print(f"  residual   {name}: {left:+.2f} samples  ({how})")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", required=True)
    ap.add_argument("--modeserv", required=True)
    ap.add_argument("--mode", action="append", required=True,
                    help="a source mode, repeatable")
    ap.add_argument("--output", default="1080p",
                    help="the output asked for; a mode the encoder cannot "
                         "carry at the source's rate falls back and the "
                         "reading follows it")
    args = ap.parse_args()

    device = hdmi_capture.device()
    host, where = args.host, args.modeserv
    was = {"output": gbs_unit.setting(host, "output"),
           "shaping": gbs_unit.shaping(host),
           "aspect": gbs_unit.get_json(host, "/geometry")[1].get("aspect"),
           "sync": gbs_unit.mode_serv(where, "SYNC")}
    if not gbs_unit.choose_output(host, args.output):
        sys.exit(f"the output never reached {args.output}")
    if not gbs_unit.want_shaping(host, True):
        sys.exit("the shape is not being applied")
    if not gbs_unit.autosave(host, False):
        sys.exit("the framing table would not stop autosaving")
    try:
        for mode in args.mode:
            report(mode, {csync: leg(host, where, device, mode, csync)
                          for csync in (False, True)})
    finally:
        gbs_unit.set_sync_type(where, " SYNC 1 " in was["sync"] + " ")
        gbs_unit.mode_serv(where, f"MODE {BENCH_MODE}")
        gbs_unit.show_card(where)
        if was["output"]:
            gbs_unit.restore_output_mode(host, was["output"])
        gbs_unit.want_shaping(host, was["shaping"])
        if was["aspect"]:
            gbs_unit.choose_aspect(host, was["aspect"])
        gbs_unit.autosave(host, True)


if __name__ == "__main__":
    main()
